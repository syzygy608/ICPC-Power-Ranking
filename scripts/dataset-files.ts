import { readFile, writeFile, mkdir, rename, unlink } from "node:fs/promises";
import { dirname, join, basename } from "node:path";
import { createHash, randomUUID } from "node:crypto";
import { validateDataset } from "../shared/validation";
import type { Dataset } from "../shared/types";

async function atomicJson(path: string, value: unknown) {
  await atomicText(path, JSON.stringify(value, null, 2) + "\n");
}
async function atomicText(path: string, text: string) {
  const temp = `${path}.${randomUUID()}.tmp`;
  try {
    await writeFile(temp, text);
    await rename(temp, path);
  } catch (error) {
    await unlink(temp).catch(() => {});
    throw error;
  }
}

/** Read either a portable backup or the repository's per-contest manifest. */
export async function readDatasetFile(path: string): Promise<Dataset> {
  const raw = JSON.parse(await readFile(path, "utf8"));
  if (raw.contests !== undefined) return validateDataset(raw);
  if (
    !Array.isArray(raw.contestFiles) ||
    !raw.contestFiles.length ||
    raw.contestFiles.length > 500
  )
    throw new Error("無效的比賽資料清單");
  if (
    raw.contestFiles.some(
      (file: unknown) =>
        typeof file !== "string" ||
        !/^contests\/[A-Za-z0-9_-]+\.json$/.test(file),
    )
  )
    throw new Error("比賽檔案必須位於 contests/ 目錄");
  const { contestFiles, ...config } = raw;
  const contests = await Promise.all(
    contestFiles.map(async (file: string) =>
      JSON.parse(await readFile(join(dirname(path), file), "utf8")),
    ),
  );
  return validateDataset({ ...config, contests });
}

/** Validate everything before writing; unchanged contest files keep identical bytes. */
export async function writeSplitDataset(path: string, input: Dataset) {
  const { contests, ...config } = validateDataset(input);
  const directory = dirname(path);
  await mkdir(join(directory, "contests"), { recursive: true });
  const contestFiles = contests.map((contest) => {
    const name = /^[A-Za-z0-9_-]{1,160}$/.test(contest.id)
      ? contest.id
      : `contest-${createHash("sha256").update(contest.id).digest("hex")}`;
    return `contests/${name}.json`;
  });
  if (new Set(contestFiles).size !== contestFiles.length)
    throw new Error("比賽檔名衝突，請調整比賽 ID");
  for (let i = 0; i < contests.length; i++)
    await atomicJson(join(directory, contestFiles[i]), contests[i]);
  await atomicJson(path, { ...config, contestFiles });
  // Static imports work in Vite and Bun; adding a contest regenerates this registry.
  const imports = contestFiles.map(
    (file, i) => `import contest${i} from ${JSON.stringify(`./${file}`)};`,
  );
  await atomicText(
    join(directory, "index.ts"),
    [
      "// Generated by bun run publish-data; do not edit by hand.",
      `import manifest from ${JSON.stringify(`./${basename(path)}`)};`,
      ...imports,
      "const { contestFiles, ...config } = manifest;",
      `export default { ...config, contests: [${contests.map((_, i) => `contest${i}`).join(", ")}] };`,
      "",
    ].join("\n"),
  );
}

export async function writeDatasetFile(path: string, data: Dataset) {
  const current = JSON.parse(await readFile(path, "utf8"));
  if (Array.isArray(current.contestFiles)) await writeSplitDataset(path, data);
  else await atomicJson(path, validateDataset(data));
}
